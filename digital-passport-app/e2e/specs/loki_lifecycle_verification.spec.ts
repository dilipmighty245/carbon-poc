import { test, expect } from '@playwright/test';
import { RegistrationPage } from '../pages/RegistrationPage';
import { LoginPage } from '../pages/LoginPage';
import { ProductSetupPage } from '../pages/ProductSetupPage';
import { PassportPage } from '../pages/PassportPage';
import { FacilitiesPage } from '../pages/FacilitiesPage';

test('organisation registration through independent verification and agency lodging', async ({ page, request }) => {
  const runId = Date.now();
  const batchId = `LOKI-${runId}`;
  const ownerEmail = `loki-${runId}@example.test`;
  const password = 'LokiPassword2026!';
  const registration = new RegistrationPage(page);
  await registration.goto();
  await registration.completeAccountOwnerStep('Loki Admin', '+44 20 7946 0192', password, ownerEmail);
  await registration.completeLegalIdentityStep('Loki', `REG-LOKI-${runId}`);
  await registration.completeRemainingSteps();
  await registration.submitRegistration();
  const tenantId = await page.evaluate(() => localStorage.getItem('saurient_tenant_id'));
  expect(tenantId).toBeTruthy();
  await registration.proceedToLogin();
  await new LoginPage(page).login(password, ownerEmail);
  expect(await page.evaluate(() => localStorage.getItem('saurient_tenant_id'))).toBe(tenantId);
  const facilities = new FacilitiesPage(page);
  await facilities.goto();
  await facilities.selectFacilitiesTab();
  await facilities.createFacility('Loki Plant', '42 Example Road, Hyderabad, India');
  const product = new ProductSetupPage(page);
  await product.goto();
  await product.createBatch({ productName: 'Loki Carbon Steel', commodity: 'Metals & Minerals', facilityName: 'Loki Plant', batchId, fuelLiters: 1500, electricityKwh: 3500 });
  const passport = new PassportPage(page);
  await passport.verifyReadinessAndProceed(batchId);
  await passport.authorizeAndIssue('Passport Officer', 'TEST-LOKI-KEY');
  const lodgingResponse = page.waitForResponse(resp => resp.url().includes('/submit-agency') && resp.request().method() === 'POST');
  await page.getByRole('button', { name: 'Submit to EU CBAM Agency' }).click();
  expect((await lodgingResponse).status()).toBe(200);
  await expect(page).toHaveURL(/\/passport\/registry$/);
  const response = await request.get('/api/v1/passports', { headers: { 'X-Tenant-ID': tenantId! } });
  expect(response.status()).toBe(200);
  const passports = await response.json();
  const issued = passports.find((p: any) => p.product_summary?.batch_number === batchId);
  expect(issued).toBeDefined();
  expect(issued.passport_metadata.status).toBe('SubmittedToAgency');
  expect(issued.passport_metadata.tenant_id).toBe(tenantId);
  expect(issued.product_summary.tenant_id).toBe(tenantId);
  expect(issued.product_summary.producer_organization).toBe('Loki');
  const unrelated = await request.get('/api/v1/passports', { headers: { 'X-Tenant-ID': `unrelated-${runId}` } });
  expect(unrelated.status()).toBe(200);
  expect(await unrelated.json()).toEqual([]);
});
